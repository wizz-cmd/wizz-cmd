import { launch, fp, log, check } from './qa3_diffreview_lib.mjs';
import path from 'path';
const t = await launch({ html: path.resolve('out/qa3/diffreview/host.html'), viewport: { width: 1000, height: 700 } });
const page = t.page; const wait = (ms) => page.waitForTimeout(ms);
await wait(800);
const frame = page.frames().find((f) => f !== page.mainFrame());
const info = () => frame.evaluate(() => ({ holds: __fizzpop._main.holds(), scene: __fizzpop.scene(), paused: __fizzpop._main.paused(), ctx: __fizzpop.AUDIO._state().ctxState }));
await frame.waitForFunction(() => !!window.__fizzpop); await frame.evaluate(() => __fizzpop.scene());
await wait(500);
await frame.evaluate(() => __fizzpop.goto('play', { players: 1, level: 2, seed: 1 }));
await page.mouse.click(400, 400); await wait(600);
let s = await info(); log('start', JSON.stringify(s));
check('IF1 visible iframe: no holds', s.holds.length === 0 && !s.paused, s);
await page.evaluate(() => window.scrollTo(0, 1500)); await wait(900);
s = await info(); log('scrolled away', JSON.stringify(s));
check('IF2 iframe scrolled out of view -> offscreen hold + game paused', s.holds.includes('offscreen') && s.paused, s);
await page.evaluate(() => window.scrollTo(0, 150)); await wait(700);
s = await info(); log('scrolled back (iframe at top partially visible)', JSON.stringify(s));
check('IF3 scrolled back -> hold released (game stays on pause menu)', !s.holds.includes('offscreen') && s.paused, s);
// partially visible: only 5 px of the iframe in view
await page.evaluate(() => window.scrollTo(0, 200 + 600 - 700 + 5 + 650)); await wait(700);
const scrollY = await page.evaluate(() => scrollY);
s = await info(); log('barely visible, scrollY', scrollY, JSON.stringify(s));
await page.evaluate(() => { document.getElementById('f').style.display = 'none'; }); await wait(700);
s = await info().catch((e) => ({ err: String(e).slice(0, 80) })); log('display:none', JSON.stringify(s));
await page.evaluate(() => { document.getElementById('f').style.display = 'block'; window.scrollTo(0, 150); }); await wait(900);
s = await info(); log('display:block again', JSON.stringify(s));
check('IF4 display:none then block again: holds cleared', s.holds.length === 0, s);
log('errors', t.errors);
await t.close();
