const b = await boot({ players: 2, level: 30, seed: 5, god: true, skipIntro: false });
const P = b.page;
const shot = (n) => canvasShot(P, OUT + '/shot_' + n + '.png', { scale: 3 });
await P.evaluate(() => { fz.step(100); });
