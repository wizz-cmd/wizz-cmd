await shot('boss_telegraph');
await P.evaluate(() => { const D = fz.Game.debug, S = D._S(); S.enemies[0].hp = 9; for (let i = 0; i < 5; i++) D.spawn('thunder', 40 + i * 30, 150); D.setHurryTimer(150 * 60 - 3); fz.step(8); });
